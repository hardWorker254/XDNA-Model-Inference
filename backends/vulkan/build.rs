//! The shaders, compiled from WGSL to SPIR-V at BUILD time.
//!
//! # Why at build time and not at start-up
//!
//! A shader that fails to compile is a bug in this repository, and a bug in
//! this repository should stop the build rather than the run. Doing it here
//! also means the runtime carries no WGSL compiler and the `.spv` words are
//! `&'static` and aligned -- `create_shader_module` takes `&[u32]` and a
//! `include_bytes!` of the same words would not be aligned to four.
//!
//! The output is a `.rs` file rather than a `.spv` beside it because a
//! generated source is checked by `cargo` and a generated binary blob is a
//! file whose format nothing verifies.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

use naga::back::spv;
use naga::front::wgsl;
use naga::valid::{Capabilities, ValidationFlags, Validator};

/// The shaders, by the name the backend asks for them.
const SHADERS: [(&str, &str); 7] = [
    ("GEMM", "gemm"),
    ("GELU", "gelu"),
    ("LAYERNORM", "layernorm"),
    ("SOFTMAX", "softmax"),
    ("ATTENTION", "attention"),
    ("ADD", "add"),
    ("MUL", "mul"),
];

fn main() {
    // One line per shader, not one for the directory: editing a file's
    // contents does not change the directory's mtime, and a build that
    // silently keeps the old SPIR-V is a gate that tests the previous
    // shader.
    for (_, file) in SHADERS {
        println!("cargo:rerun-if-changed=shaders/{file}.wgsl");
    }
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("shaders_spv.rs");
    let mut code = String::from(
        "// @generated by backends/vulkan/build.rs -- WGSL compiled to SPIR-V.\n\
         // Do not edit; edit the .wgsl file and rebuild.\n",
    );

    for (const_name, file) in SHADERS {
        let path = format!("shaders/{file}.wgsl");
        let source = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{path}: {e}"));
        let module = wgsl::parse_str(&source).unwrap_or_else(|e| {
            panic!("{path}: WGSL does not parse: {e}")
        });
        let info = Validator::new(ValidationFlags::all(), Capabilities::empty())
            .validate(&module)
            .unwrap_or_else(|e| panic!("{path}: WGSL does not validate: {e:?}"));
        let words = spv::write_vec(
            &module,
            &info,
            &spv::Options {
                lang_version: (1, 3),
                ..Default::default()
            },
            None,
        )
        .unwrap_or_else(|e| panic!("{path}: SPIR-V was not written: {e:?}"));

        writeln!(code, "/// `{file}.wgsl`, as SPIR-V 1.3.").unwrap();
        writeln!(code, "pub const {const_name}: &[u32] = &[").unwrap();
        for chunk in words.chunks(8) {
            for w in chunk {
                write!(code, "0x{w:08x},").unwrap();
            }
            code.push('\n');
        }
        writeln!(code, "];").unwrap();
    }

    fs::write(&out, code).unwrap_or_else(|e| panic!("{}: {e}", out.display()));
}
