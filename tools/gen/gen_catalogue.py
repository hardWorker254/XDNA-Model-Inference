# NpuEmbeddings -- turn the built-in catalogue into a Rust table.
#
#   python tools/gen/gen_catalogue.py
#
# WHY A GENERATOR AND NOT A JSON READ AT RUN TIME
# ----------------------------------------------
# The catalogue is DATA, and it lives in `core/npum-families/data/catalogue.json`
# -- that file is the source of truth and a reader can diff it. But the
# runtime should not need a JSON parser and a filesystem lookup to answer
# "which models does this build know", because that answer is asked on every
# refusal and every `list`.
#
# So: the JSON is the source of truth, this script turns it into a static
# Rust table, and the table is what ships. The JSON stays in the tree, so
# the data is still reviewable as data.
#
# WHAT THE TABLE IS FOR
# ---------------------
# Three things, and all three are the TABLE'S SHAPE rather than its
# contents:
#
# * the `list` table's rows -- name, state, layers, hidden, pooling, size,
#   note;
# * the refusal for a model this build does not know, which LISTS the
#   models it does know;
# * the geometry the packer cross-checks against the downloaded
#   config.json.
#
# Env: any Python 3 (no NPU, no torch).

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "core" / "npum-families" / "data" / "catalogue.json"
OUT = REPO / "core" / "npum-families" / "src" / "catalogue_data.rs"


def rust_str(value: str) -> str:
    """A Rust string literal for a value that may hold anything."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def main() -> int:
    if not SRC.exists():
        print(f"error: {SRC} is not there", file=sys.stderr)
        return 1
    data = json.loads(SRC.read_text(encoding="utf-8"))
    rows = data["models"]

    parts: list[str] = []
    parts.append(
        """//===- catalogue_data.rs ------------------------------------*- rust -*-===//
//
// GENERATED by tools/gen/gen_catalogue.py -- DO NOT EDIT.
// SPDX-License-Identifier: Apache-2.0
//
// The BUILT-IN catalogue: the models this build knows how to fetch and how
// to run.
//
// The source of truth is core/npum-families/data/catalogue.json. This file
// is what ships, because the answer "which models does this build know" is
// asked on every refusal and every `list`, and it should not cost a JSON
// parser and a filesystem lookup.
//
// The geometry is a DESCRIPTION for the table, never an assumption the
// packer relies on: the packer reads the checkpoint's own config.
//
//===----------------------------------------------------------------------===//

/// The models this build knows.
pub static CATALOGUE: &[CatalogueEntry] = &[
"""
    )
    for row in rows:
        parts.append(
            "    CatalogueEntry {\n"
            f"        name: {rust_str(row['name'])},\n"
            f"        repo: {rust_str(row['repo'])},\n"
            f"        sha256: {rust_str(row['sha256'])},\n"
            f"        pooling: {rust_str(row['pooling'])},\n"
            f"        hidden: {row['hidden']},\n"
            f"        layers: {row['layers']},\n"
            f"        heads: {row['heads']},\n"
            f"        ffn: {row['ffn']},\n"
            f"        tile_n: {row['tile_n']},\n"
            f"        download_mb: {row['download_mb']},\n"
            f"        note: {rust_str(row['note'])},\n"
            "    },\n"
        )
    parts.append("];\n")

    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}  ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
